//! Build-time codegen: embed `data/seeds/*.json` into the binary.
//!
//! Walks the workspace `data/seeds/` directory at compile time and emits
//! `$OUT_DIR/shipped_seeds.rs` containing
//!
//! ```ignore
//! pub static SHIPPED_SEED_PACKS: &[(&str, &str)] = &[
//!     ("feather", "{...JSON...}"),
//!     ...
//! ];
//! ```
//!
//! Consumed by `crates/core/src/seed_pack.rs` via `include!`.
//!
//! Adding, removing, or editing a pack file triggers a rebuild via
//! `cargo:rerun-if-changed=` directives on both the directory and each
//! file. Any non-`.json` file is silently skipped so editor swap files
//! don't crash the build; an `example.json.txt` template (Stage 5) is
//! also skipped because of the `.json` extension check.

use std::ffi::OsStr;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let seeds_dir = manifest.join("../../data/seeds");

    println!("cargo:rerun-if-changed={}", seeds_dir.display());
    println!("cargo:rerun-if-changed=build.rs");

    let mut entries: Vec<(String, String)> = Vec::new();
    if seeds_dir.is_dir() {
        let read = fs::read_dir(&seeds_dir).unwrap_or_else(|e| {
            panic!(
                "build.rs: cannot read {}: {e}",
                seeds_dir.display()
            )
        });
        for entry in read.flatten() {
            let path = entry.path();
            if path.extension().and_then(OsStr::to_str) != Some("json") {
                continue;
            }
            // rerun on edit to any individual pack file
            println!("cargo:rerun-if-changed={}", path.display());
            let stem = path
                .file_stem()
                .and_then(OsStr::to_str)
                .unwrap_or_else(|| panic!("build.rs: bad pack filename: {}", path.display()))
                .to_string();
            let raw = fs::read_to_string(&path).unwrap_or_else(|e| {
                panic!("build.rs: cannot read {}: {e}", path.display())
            });
            entries.push((stem, raw));
        }
    }
    // Stable order so the generated source is reproducible.
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let out_dir = std::env::var_os("OUT_DIR").expect("OUT_DIR not set by cargo");
    let out_path = PathBuf::from(out_dir).join("shipped_seeds.rs");

    let mut body = String::new();
    body.push_str("// @generated by build.rs — do not edit by hand.\n");
    body.push_str("pub static SHIPPED_SEED_PACKS: &[(&str, &str)] = &[\n");
    for (stem, raw) in &entries {
        // `r#"…"#` raw-string with one #; if any pack ever contains the
        // literal `"#` that would break compilation, escalate the # count.
        if raw.contains("\"#") {
            panic!(
                "build.rs: pack {} contains the literal `\"#`; please re-author with a single # raw string boundary",
                stem
            );
        }
        body.push_str(&format!("    (\"{stem}\", r#\"{raw}\"#),\n"));
    }
    body.push_str("];\n");

    fs::write(&out_path, body).unwrap_or_else(|e| {
        panic!("build.rs: cannot write {}: {e}", out_path.display())
    });
}
