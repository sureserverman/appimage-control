#!/usr/bin/env python3
"""Check the metainfo file against the Flathub quality guidelines we can test.

Usage: check-metainfo-quality.py <metainfo.xml>

Exits 0 when every check passes, 1 when one fails (each failure is printed),
2 on a usage or parse error.
"""
import os
import re
import struct
import sys
import xml.etree.ElementTree as ET

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCREENSHOT_DIR = "docs/screenshots/"
# Screenshot URLs must point at this repo's main branch; the path after it is checked locally.
SCREENSHOT_URL_PREFIX = "https://raw.githubusercontent.com/sureserverman/appimage-control/main/"
SCREENSHOT_SIZE = (1000, 700)
XML_LANG = "{http://www.w3.org/XML/1998/namespace}lang"


def text_of(el):
    return " ".join("".join(el.itertext()).split()) if el is not None else ""


def untranslated(parent, tag):
    """The element without xml:lang (the source text), or None."""
    for el in parent.findall(tag):
        if el.get(XML_LANG) is None:
            return el
    return None


def png_size(path):
    with open(path, "rb") as f:
        head = f.read(24)
    if head[:8] != b"\x89PNG\r\n\x1a\n" or head[12:16] != b"IHDR":
        return None
    return struct.unpack(">II", head[16:24])


def check_image(n, url):
    """Errors for one screenshot image URL: this repo, docs/screenshots/, a 1000x700 PNG."""
    rel = url[len(SCREENSHOT_URL_PREFIX):] if url.startswith(SCREENSHOT_URL_PREFIX) else ""
    if not re.fullmatch(re.escape(SCREENSHOT_DIR) + r"[A-Za-z0-9._-]+\.png", rel):
        return [f"screenshot {n} image is not a PNG under {SCREENSHOT_URL_PREFIX}"
                f"{SCREENSHOT_DIR}: {url!r}"]
    local = os.path.join(REPO, rel)
    if not os.path.isfile(local):
        return [f"screenshot {n} file is missing: {rel}"]
    size = png_size(local)
    if size != SCREENSHOT_SIZE:
        return [f"screenshot {n} {rel} is {size}, want "
                f"{SCREENSHOT_SIZE[0]}x{SCREENSHOT_SIZE[1]} PNG"]
    return []


def check_screenshots(root):
    errors = []
    shots = root.findall("./screenshots/screenshot")
    if not 3 <= len(shots) <= 6:
        errors.append(f"{len(shots)} screenshots, want 3 to 6")
    defaults = [s for s in shots if s.get("type") == "default"]
    if len(defaults) != 1:
        errors.append(f"{len(defaults)} screenshots marked type=\"default\", want exactly 1")
    for n, shot in enumerate(shots, 1):
        if untranslated(shot, "caption") is None:
            errors.append(f"screenshot {n} has no caption")
        # Every caption, translations included, follows the caption rules.
        for el in shot.findall("caption"):
            caption = text_of(el)
            lang = el.get(XML_LANG)
            where = f"screenshot {n} caption" + (f" ({lang})" if lang else "")
            if not caption:
                errors.append(f"{where} is empty")
            elif caption.endswith("."):
                errors.append(f"{where} ends with a period: {caption!r}")
            elif caption[0].isdigit():
                errors.append(f"{where} starts with a digit: {caption!r}")
        # Thumbnails are generated by Flathub; every other image is ours and must exist.
        images = [i for i in shot.findall("image") if i.get("type") != "thumbnail"]
        if not images:
            errors.append(f"screenshot {n} has no source image")
        for img in images:
            errors.extend(check_image(n, text_of(img)))
    return errors


def check(path):
    errors = []
    root = ET.parse(path).getroot()

    name = text_of(untranslated(root, "name"))
    summary = text_of(untranslated(root, "summary"))
    if not name:
        errors.append("no untranslated <name>")
    if not 10 <= len(summary) <= 35:
        errors.append(f"summary is {len(summary)} characters, want 10 to 35: {summary!r}")
    if summary.endswith("."):
        errors.append(f"summary ends with a period: {summary!r}")
    if name and name.lower() in summary.lower():
        errors.append(f"summary repeats the app name {name!r}: {summary!r}")

    description = untranslated(root, "description")
    paragraphs = ([p for p in description.findall("p") if p.get(XML_LANG) is None]
                  if description is not None else [])
    if not paragraphs:
        errors.append("description has no <p>")
    else:
        first = text_of(paragraphs[0]).lower()
        if not re.search(r"\binstances?\b|\bcop(y|ies)\b", first):
            errors.append("description's first paragraph does not mention instances or copies")
        if not re.search(r"checksums?|sha-?256|\bhash(es)?\b", first):
            errors.append("description's first paragraph does not mention checksums")
    items = description.findall(".//li") if description is not None else []
    if len(items) > 10:
        errors.append(f"description has {len(items)} list items, want at most 10")

    colors = root.findall("./branding/color[@type='primary']")
    by_scheme = {c.get("scheme_preference"): (c.text or "").strip().lower() for c in colors}
    if len(colors) != 2 or set(by_scheme) != {"light", "dark"}:
        errors.append("branding needs two primary colors, scheme_preference light and dark")
    elif by_scheme["light"] == by_scheme["dark"]:
        errors.append("light and dark brand colors are the same")

    if not root.findall("./keywords/keyword"):
        errors.append("no <keyword> entries")

    errors.extend(check_screenshots(root))
    return errors


def main(argv):
    if len(argv) != 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    try:
        errors = check(argv[1])
    except (OSError, ET.ParseError) as e:
        print(f"cannot read {argv[1]}: {e}", file=sys.stderr)
        return 2
    for e in errors:
        print(f"FAIL: {e}")
    if errors:
        return 1
    print("OK: metainfo meets the checked quality guidelines")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
